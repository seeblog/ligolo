// strgen reads strings.manifest (KEY = VALUE per line) and generates
// obfuscated_strings.go: each string becomes a random-key XOR ciphertext
// plus a sync.OnceValues accessor, so no plaintext literal ever appears in
// the compiled binary. Re-run to rotate keys (new ciphertext per build).
//
// Usage: go run tools/strgen
package main

import (
	"crypto/rand"
	"fmt"
	"os"
	"strings"
)

func main() {
	data, err := os.ReadFile("strings.manifest")
	if err != nil {
		fmt.Fprintln(os.Stderr, "strgen:", err)
		os.Exit(1)
	}

	var sb strings.Builder
	sb.WriteString("// Code generated by tools/strgen from strings.manifest. DO NOT EDIT.\n")
	sb.WriteString("// Regenerate with: go run tools/strgen\n")
	sb.WriteString("package relaykit\n\n")
	sb.WriteString("import \"sync\"\n\n")
	sb.WriteString("// sx decodes (XOR) a ciphertext with its key. Pure: never mutates ct.\n")
	sb.WriteString("func sx(ct []byte, k byte) string {\n")
	sb.WriteString("\tout := make([]byte, len(ct))\n")
	sb.WriteString("\tfor i := range ct {\n")
	sb.WriteString("\t\tout[i] = ct[i] ^ k\n")
	sb.WriteString("\t}\n")
	sb.WriteString("\treturn string(out)\n")
	sb.WriteString("}\n\n")
	sb.WriteString("// strCache lazily decodes each string exactly once, concurrency-safe.\n")
	sb.WriteString("type strCache struct {\n")
	sb.WriteString("\tonce sync.Once\n")
	sb.WriteString("\tv    string\n")
	sb.WriteString("\tfn   func() string\n")
	sb.WriteString("}\n\n")
	sb.WriteString("func (c *strCache) Get() string {\n")
	sb.WriteString("\tc.once.Do(func() { c.v = c.fn() })\n")
	sb.WriteString("\treturn c.v\n")
	sb.WriteString("}\n\n")

	accessors := []string{}

	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimRight(line, "\r")
		if line == "" || strings.HasPrefix(line, "//") {
			continue
		}
		eq := strings.Index(line, " = ")
		if eq < 0 {
			continue
		}
		key := strings.TrimSpace(line[:eq])
		val := strings.TrimSpace(line[eq+3:])
		if key == "" || val == "" {
			continue
		}

		// random key + ciphertext
		var kb [1]byte
		rand.Read(kb[:])
		k := kb[0] | 1 // avoid 0 (plaintext) - any odd key is fine
		ct := make([]byte, len(val))
		for i := 0; i < len(val); i++ {
			ct[i] = val[i] ^ k
		}

		// identifiers
		rawName := "ct_" + key
		keyName := "k_" + key
		fnName := "Str_" + key

		sb.WriteString(fmt.Sprintf("var %s = []byte{", rawName))
		for _, b := range ct {
			sb.WriteString(fmt.Sprintf("0x%02x, ", b))
		}
		sb.WriteString("}\n")
		sb.WriteString(fmt.Sprintf("const %s byte = 0x%02x\n", keyName, k))
		sb.WriteString(fmt.Sprintf("var %s = &strCache{fn: func() string { return sx(%s, %s) }}\n\n", fnName, rawName, keyName))
		accessors = append(accessors, key)
	}

	if err := os.WriteFile("obfuscated_strings.go", []byte(sb.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "strgen:", err)
		os.Exit(1)
	}
	fmt.Printf("strgen: generated %d obfuscated strings\n", len(accessors))
}

